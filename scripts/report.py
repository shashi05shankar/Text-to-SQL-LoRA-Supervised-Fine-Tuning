"""Write the results tables into the README from `metrics.json` -- and audit them.

The README is generated between markers, never hand-edited. `--check` re-renders and
compares, so a number that drifted from the artifact (or was typed in by hand) fails
loudly. That is the mechanism behind the project's central rule: no metric appears in the
README that did not come out of a real run.

    python scripts/report.py                    # rewrite README.md
    python scripts/report.py --check README.md  # verify; non-zero exit on drift
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from text2sql_lora.config import Paths

BEGIN = "<!-- BEGIN RESULTS (generated by scripts/report.py -- do not hand-edit) -->"
END = "<!-- END RESULTS -->"

SYSTEM_LABELS = {
    "base_zero_shot": "Base, zero-shot",
    "base_few_shot": "Base, 3-shot",
    "lora_zero_shot": "**LoRA fine-tuned**",
}
SYSTEM_ORDER = ["base_zero_shot", "base_few_shot", "lora_zero_shot"]


# True (unquantized) parameter counts, derived from each model's published config:
# vocab*hidden embeddings + layers * (attention + MLP + norms). Needed because
# `total_params` in the manifest is NOT the model's parameter count -- see below.
TRUE_PARAM_COUNTS = {
    "Qwen/Qwen2.5-1.5B-Instruct": 1_543_714_304,
}


def trainable_share_note(manifest: dict) -> str:
    """Explain what fraction of the model LoRA actually trains.

    The manifest's `total_params` comes from summing `p.numel()` over a **4-bit** model,
    and bitsandbytes packs two 4-bit weights into each uint8 element. So the number the
    model reports (907M for Qwen2.5-1.5B) is roughly half the real parameter count, and
    naively dividing by it overstates LoRA's share -- 2.04% instead of 1.20%.

    Reporting the flattering number would be exactly the kind of thing this project is
    built to avoid, so both are given, with the reason.
    """
    trainable = manifest.get("trainable_params", 0)
    packed = manifest.get("total_params", 0)
    base_model = manifest.get("base_model", "")
    true_total = TRUE_PARAM_COUNTS.get(base_model)

    if not (trainable and packed):
        return ""

    note = (
        f"That is **{100 * trainable / true_total:.2f}% of the base model's "
        f"{true_total:,} parameters**."
        if true_total
        else ""
    )
    return (
        f"{note} The run's own manifest records {packed:,} total params and "
        f"{100 * trainable / packed:.2f}%, but that count is taken over the *4-bit* "
        "model: bitsandbytes packs two weights per byte, so summing `numel()` returns "
        "about half the true parameter count and correspondingly overstates LoRA's "
        "share. The larger, more flattering figure is not the one quoted here."
    ).strip()


def render(metrics: dict) -> str:
    results = metrics["results"]
    manifest = metrics.get("manifest", {})
    headline = metrics.get("headline", {})

    lines: list[str] = ["", "### Headline", ""]

    if headline:
        base = headline["base_zero_shot_execution_accuracy"]
        tuned = headline["lora_zero_shot_execution_accuracy"]
        lines += [
            f"**Execution accuracy on Spider dev: {base:.1%} -> {tuned:.1%}** "
            f"({headline['absolute_gain']:+.1%} absolute"
            + (
                f", {headline['relative_gain']:+.0%} relative)"
                if headline.get("relative_gain") is not None
                else ")"
            ),
            "",
            f"Measured on {results['lora_zero_shot']['n']:,} held-out questions over "
            "databases that appear nowhere in training.",
            "",
        ]
        if "gain_over_few_shot" in headline:
            lines += [
                f"Against the stronger 3-shot baseline "
                f"({headline['base_few_shot_execution_accuracy']:.1%}), the gain is "
                f"{headline['gain_over_few_shot']:+.1%}.",
                "",
            ]

    lines += [
        "### All three systems, same test set",
        "",
        "| System | n | Execution accuracy | Exact match | Invalid SQL |",
        "| --- | --- | --- | --- | --- |",
    ]
    for name in SYSTEM_ORDER:
        if name not in results:
            continue
        row = results[name]
        lines.append(
            f"| {SYSTEM_LABELS.get(name, name)} | {row['n']:,} | "
            f"{row['execution_accuracy']:.4f} | {row['exact_match']:.4f} | "
            f"{row['invalid_sql_rate']:.4f} |"
        )

    if metrics.get("by_hardness"):
        buckets: dict[str, dict] = {}
        for row in metrics["by_hardness"]:
            buckets.setdefault(row["hardness"], {})[row["system"]] = row
        lines += [
            "",
            "### By query complexity",
            "",
            "Bucketing is **our own** component-count heuristic (joins / nesting / "
            "aggregates), not Yale's official Spider hardness definition.",
            "",
            "| Complexity | n | Base zero-shot | Base 3-shot | LoRA fine-tuned |",
            "| --- | --- | --- | --- | --- |",
        ]
        for bucket in ("easy", "medium", "hard", "extra"):
            if bucket not in buckets:
                continue
            entries = buckets[bucket]
            n = next(iter(entries.values()))["n"]
            cells = [
                f"{entries[name]['execution_accuracy']:.4f}" if name in entries else "-"
                for name in SYSTEM_ORDER
            ]
            lines.append(f"| {bucket} | {n:,} | " + " | ".join(cells) + " |")

    if manifest:
        hardware = manifest.get("gpu", manifest.get("device", "?"))
        lora = manifest.get("lora", {})
        lines += [
            "",
            "### Provenance",
            "",
            f"Produced by `text2sql_lora` {manifest.get('package_version', '?')} on "
            f"{manifest.get('created_utc', '?')} ({hardware}, "
            f"torch {manifest.get('torch', '?')}, "
            f"transformers {manifest.get('transformers', '?')}).",
            "",
            f"Base `{manifest.get('base_model', '?')}`, "
            f"LoRA r={lora.get('r', '?')} alpha={lora.get('alpha', '?')}, "
            f"seq {manifest.get('max_seq_len', '?')}, seed {manifest.get('seed', '?')}.",
            "",
            f"**{manifest.get('trainable_params', 0):,} trainable parameters** — the base "
            "weights never moved.",
            "",
            trainable_share_note(manifest),
            "",
            f"Trained on {manifest.get('n_train', '?'):,} examples "
            f"(monitoring split {manifest.get('n_val', '?'):,}, database-disjoint), "
            f"evaluated on {manifest.get('n_dev', '?'):,}. "
            f"Wall clock {manifest.get('wall_clock_seconds', 0) / 60:.1f} min.",
        ]
        if metrics.get("n_unexecutable_gold"):
            lines += [
                "",
                f"Note: {metrics['n_unexecutable_gold']} gold queries did not execute and "
                "are scored as incorrect for every system alike.",
            ]

    lines.append("")
    return "\n".join(lines)


def render_analysis(analysis: dict) -> str:
    """The deep-evaluation tables, from `scripts/analyze.py`."""
    if not analysis:
        return ""

    lines: list[str] = ["", "---", "", "### Is the difference real?", ""]

    lines += [
        "Wilson 95% intervals on each system, and **paired** tests on the difference. "
        "Paired because all three systems answer the same 1,034 questions — an unpaired "
        "test would discard that structure and be needlessly conservative.",
        "",
        "| System | Execution accuracy | 95% CI |",
        "| --- | --- | --- |",
    ]
    for name in SYSTEM_ORDER:
        entry = analysis["accuracy"].get(name)
        if not entry:
            continue
        lines.append(
            f"| {SYSTEM_LABELS.get(name, name)} | {entry['accuracy']:.4f} | "
            f"[{entry['ci_low']:.4f}, {entry['ci_high']:.4f}] |"
        )

    lines += [
        "",
        "| Comparison | Fixed | Broke | McNemar p | Bootstrap 95% CI on the gain | Verdict |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for comparison in analysis["comparisons"].values():
        mc = comparison["mcnemar"]
        bs = comparison.get("bootstrap", {})
        label = (
            f"{SYSTEM_LABELS.get(comparison['candidate'], comparison['candidate'])} vs "
            f"{SYSTEM_LABELS.get(comparison['baseline'], comparison['baseline'])}"
        ).replace("**", "")
        verdict = "**significant**" if mc["significant_at_05"] else "not significant"
        lines.append(
            f"| {label} | {mc['gained']} | {mc['lost']} | {mc['p_value']:.3g} | "
            f"[{bs.get('ci_low', float('nan')):+.4f}, {bs.get('ci_high', float('nan')):+.4f}] | "
            f"{verdict} |"
        )

    lines += [
        "",
        "The fine-tuning gain is far outside anything sampling noise produces. The "
        "few-shot baseline is **statistically indistinguishable** from zero-shot — its "
        "bootstrap interval straddles zero and McNemar cannot reject a coin flip. Three "
        "in-context examples did not make the base model better at this task.",
        "",
        "### How each system fails",
        "",
        "Every prediction re-executed against the real database and classified. "
        "*Invalid* means the query did not run — a grammar or schema-grounding failure. "
        "*Semantic* means it ran and returned the wrong rows — the model understood SQL "
        "and misread the question.",
        "",
        "| System | Correct | Invalid (didn't run) | Semantic (ran, wrong) | "
        "Semantic share of errors |",
        "| --- | --- | --- | --- | --- |",
    ]
    for name in SYSTEM_ORDER:
        f = analysis["failures"].get(name)
        if not f:
            continue
        lines.append(
            f"| {SYSTEM_LABELS.get(name, name)} | {f['n_correct'] / f['n']:.4f} | "
            f"{f['invalid_rate']:.4f} | {f['semantic_error_rate']:.4f} | "
            f"{f['semantic_share_of_errors']:.4f} |"
        )

    lines += [
        "",
        "The last column is the one to watch: of the questions a system gets wrong, what "
        "fraction at least *executed*. It rises across the fine-tune, meaning errors "
        "migrated from \"cannot write valid SQL against this schema\" to \"wrote valid "
        "SQL, misread the question\" — a harder and more interesting remaining problem.",
        "",
        "Most common failure modes:",
        "",
        "| Failure | Base zero-shot | LoRA fine-tuned |",
        "| --- | --- | --- |",
    ]
    base_kinds = analysis["failures"]["base_zero_shot"]["by_kind"]
    lora_kinds = analysis["failures"]["lora_zero_shot"]["by_kind"]
    interesting = [k for k in base_kinds if k != "correct"][:6]
    for kind in interesting:
        base_rate = base_kinds.get(kind, {}).get("rate", 0.0)
        lora_rate = lora_kinds.get(kind, {}).get("rate", 0.0)
        lines.append(f"| {kind} | {base_rate:.4f} | {lora_rate:.4f} |")

    lines += [
        "",
        "### What it got structurally right",
        "",
        "Execution accuracy is all-or-nothing: a query with the right joins, filter and "
        "grouping but the wrong aggregate scores exactly the same as gibberish. These "
        "metrics parse both queries into an AST (`sqlglot`) and award partial credit.",
        "",
        "**Schema grounding** — do the tables and columns named actually exist in that "
        "database? **Component matching** — does the query have gold's shape: same "
        "clauses, same join count, same aggregates? (A simplified reimplementation of "
        "the partial-credit metrics the Spider literature reports, not the official "
        "evaluator.)",
        "",
        "| System | Parses | Fully grounded | Clause F1 | Join count | Aggregate | Exact shape |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for name in SYSTEM_ORDER:
        g = analysis["grounding"].get(name, {})
        c = analysis["components"].get(name, {})
        if not g or not c:
            continue
        lines.append(
            f"| {SYSTEM_LABELS.get(name, name)} | {g['parse_rate']:.4f} | "
            f"{g['grounded_rate']:.4f} | {c['clause_f1']:.4f} | "
            f"{c['join_count_match_rate']:.4f} | {c['aggregate_match_rate']:.4f} | "
            f"{c['exact_shape_match_rate']:.4f} |"
        )

    efficiency = analysis.get("efficiency", {})
    if efficiency:
        lines += [
            "",
            "### Cost",
            "",
            "| | |",
            "| --- | --- |",
            f"| Adapter shipped | **{efficiency.get('adapter_mb', 0):.0f} MB** "
            "(vs ~3 GB for a full fine-tune checkpoint) |",
            f"| Trainable parameters | {efficiency.get('trainable_params', 0):,} |",
            f"| Hardware | {efficiency.get('gpu', '?')} (free tier) |",
            f"| Wall clock | {efficiency.get('wall_clock_hours', 0):.1f} h |",
            f"| Throughput | {efficiency.get('examples_per_second') or 0:.2f} examples/s |",
        ]

    lines.append("")
    return "\n".join(lines)


def render_experiments(experiments: dict) -> str:
    """The LoRA-vs-QLoRA comparison table, from `scripts/collect_experiments.py`.

    Only rendered once at least two arms exist -- a single arm is just the headline run
    and has nothing to compare against.
    """
    arms = experiments.get("arms", [])
    if len(arms) < 2:
        return ""

    def fmt(value, spec: str, dash: str = "—") -> str:
        return format(value, spec) if value is not None else dash

    lines = [
        "",
        "---",
        "",
        "### LoRA vs QLoRA — what the quantization actually costs",
        "",
        "The published run used QLoRA (4-bit NF4 base). QLoRA was not *required* at this "
        "size — fp16 LoRA fits a 16 GB T4 too. So this runs the identical recipe (same "
        "seed, data, split, rank, epochs, batch, LR) with **only** the base precision "
        "changed, and measures the trade.",
        "",
        "| Arm | Base precision | Execution accuracy | Wall clock | Peak VRAM | Adapter |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for arm in arms:
        precision = "4-bit NF4" if arm["quantization"] == "nf4" else "fp16"
        lines.append(
            f"| `{arm['name']}` | {precision} | "
            f"{fmt(arm['tuned_execution_accuracy'], '.4f')} | "
            f"{fmt(arm['wall_clock_hours'], '.1f')} h | "
            f"{fmt(arm['peak_vram_gb'], '.2f')} GB | "
            f"{fmt(arm['adapter_mb'], '.0f')} MB |"
        )

    # Draw the conclusion from the data rather than asserting it.
    nf4 = next((a for a in arms if a["quantization"] == "nf4"), None)
    fp16 = next((a for a in arms if a["quantization"] == "none"), None)
    if nf4 and fp16 and nf4["tuned_execution_accuracy"] and fp16["tuned_execution_accuracy"]:
        acc_gap = fp16["tuned_execution_accuracy"] - nf4["tuned_execution_accuracy"]
        lines += ["", _experiment_verdict(nf4, fp16, acc_gap)]

    lines.append("")
    return "\n".join(lines)


def _experiment_verdict(nf4: dict, fp16: dict, acc_gap: float) -> str:
    """One honest sentence about which arm won, computed from the arms."""
    parts = []
    if abs(acc_gap) < 0.01:
        parts.append(
            f"Accuracy is effectively tied ({acc_gap:+.4f}, within a point)"
        )
    elif acc_gap > 0:
        parts.append(f"fp16 LoRA is **{acc_gap:+.4f}** more accurate")
    else:
        parts.append(f"4-bit QLoRA is **{-acc_gap:+.4f}** more accurate")

    if nf4.get("wall_clock_hours") and fp16.get("wall_clock_hours"):
        faster = "fp16" if fp16["wall_clock_hours"] < nf4["wall_clock_hours"] else "4-bit"
        ratio = max(nf4["wall_clock_hours"], fp16["wall_clock_hours"]) / min(
            nf4["wall_clock_hours"], fp16["wall_clock_hours"]
        )
        parts.append(f"{faster} trained {ratio:.2f}x faster")

    if nf4.get("peak_vram_gb") and fp16.get("peak_vram_gb"):
        parts.append(
            f"4-bit used {fp16['peak_vram_gb'] - nf4['peak_vram_gb']:+.2f} GB less VRAM"
        )

    return (
        ". ".join(parts)
        + ". Both ran on the same GPU at the same batch and sequence length, which is "
        "what makes the wall-clock and VRAM figures comparable."
    )


def splice(readme: str, block: str) -> str:
    if BEGIN not in readme or END not in readme:
        raise SystemExit(f"README is missing the {BEGIN!r} / {END!r} markers")
    head, rest = readme.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{BEGIN}\n{block}{END}{tail}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", type=Path, default=None, help="verify instead of writing")
    parser.add_argument("--readme", type=Path, default=Path("README.md"))
    args = parser.parse_args()

    paths = Paths()
    metrics_path = paths.metrics_json()
    if not metrics_path.exists():
        print(
            f"No {metrics_path}. The training run has not been ingested, so there are no "
            "numbers to report. See docs/kaggle_run.md."
        )
        return 1

    metrics = json.loads(metrics_path.read_text(encoding="utf-8"))

    # The deep analysis is optional: `metrics.json` alone is enough to report the
    # headline. If `scripts/analyze.py` has been run, its tables are appended.
    analysis_path = paths.artifacts_dir / "analysis.json"
    analysis = (
        json.loads(analysis_path.read_text(encoding="utf-8"))
        if analysis_path.exists()
        else {}
    )

    experiments_path = paths.artifacts_dir / "experiments.json"
    experiments = (
        json.loads(experiments_path.read_text(encoding="utf-8"))
        if experiments_path.exists()
        else {}
    )

    block = render(metrics) + render_analysis(analysis) + render_experiments(experiments)

    target = args.check or args.readme
    readme = target.read_text(encoding="utf-8")
    updated = splice(readme, block)

    if args.check:
        if updated.strip() != readme.strip():
            print(
                f"FAIL: {target} does not match {metrics_path}. Some number in the README "
                "was hand-edited or is stale. Run `python scripts/report.py` to fix."
            )
            return 1
        print(f"PASS: every number in {target} traces to {metrics_path}")
        return 0

    target.write_text(updated, encoding="utf-8")
    print(f"wrote results into {target} from {metrics_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
